#!/usr/bin/env python3
"""Vendoring of capability modules (docs/PLAN-capabilities-repo.md, Q3). Standard library only.

A capability package with `module` brings Nix code. The Nix evaluation must not read a mutable folder under /var/lib, so the verified package folder is
copied into the checkout: <checkout>/vendor/capabilities/<name>/, and <checkout>/vendor/capabilities.lock records what capabilities/default.nix
may load (the sha256 of every *.nix file, as builtins.hashFile returns it). The lock is generated, never edited; the same input gives the same bytes.

  pkg.py vendor --from <package folder> --to <checkout> [--repo R --tag T --commit C --tree X]   copy the folder, write its lock entry
  pkg.py unvendor <name> --to <checkout>                                                          delete the folder and the lock entry
  pkg.py vendor-check --to <checkout>                                                                    folder and lock agree (exit 1 and the package name when not)

The same functions are used by `hs pkg install|update|remove` and by CI (scripts/dev/nix-matrix.sh --vendor).
"""
import hashlib
import os
import re
import shutil
import stat
import sys
import tomllib

NAME = re.compile(r"^[a-z][a-z0-9-]{0,40}$")
NIX_FILE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*\.nix$")
ORDER = ("version", "repo", "tag", "commit", "tree")


class Refused(Exception):
    pass


def vendor_dir(checkout):
    return os.path.join(checkout, "vendor", "capabilities")


def lock_file(checkout):
    return os.path.join(checkout, "vendor", "capabilities.lock")


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def nix_hashes(folder):
    """{file name: sha256} of every *.nix file of the folder. A *.nix file in a subfolder is refused: a module may import only files of its own folder."""
    out = {}
    for base, dirs, files in os.walk(folder):
        dirs.sort()
        for n in sorted(files):
            if not n.endswith(".nix"):
                continue
            rel = os.path.relpath(os.path.join(base, n), folder).replace(os.sep, "/")
            if "/" in rel:
                raise Refused("%s: a module may import only .nix files of its own folder, not %s" % (os.path.basename(folder), rel))
            if not NIX_FILE.match(n):
                raise Refused("%s: %s is not an allowed file name for a Nix file" % (os.path.basename(folder), n))
            out[n] = sha256_file(os.path.join(base, n))
    return out


def read_lock(checkout):
    try:
        with open(lock_file(checkout), "rb") as f:
            return tomllib.load(f)
    except (OSError, tomllib.TOMLDecodeError):
        return {}


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_lock(lock):
    lines = ["# Generated by hs pkg (scripts/lib/pkg_vendor.py). Never edit: capabilities/default.nix trusts exactly these hashes.\n"]
    for name in sorted(lock):
        e = lock[name]
        lines.append("\n[%s]\n" % name)
        for k in ORDER:
            if e.get(k) not in (None, ""):
                lines.append("%s = %s\n" % (k, q(e[k])))
        lines.append("\n[%s.nix]\n" % name)
        for f, h in sorted(e.get("nix", {}).items()):
            lines.append("%s = %s\n" % (q(f), q(h)))
    return "".join(lines)


def write_lock(checkout, lock):
    """Atomic: .new next to it, then rename. An empty lock removes the file."""
    f = lock_file(checkout)
    if not lock:
        try:
            os.remove(f)
        except OSError:
            pass
        return
    os.makedirs(os.path.dirname(f), exist_ok=True)
    with open(f + ".new", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_lock(lock))
    os.replace(f + ".new", f)


def rm_tree(path):
    def onerr(fn, p, _):
        os.chmod(p, stat.S_IRWXU)
        fn(p)
    shutil.rmtree(path, onerror=onerr)


def vendor(src, checkout, info=None):
    """Copy the package folder `src` to <checkout>/vendor/capabilities/<name>/ and record it in the lock. `info` = repo, tag, commit, tree
    (what is known; CI has no tag). Returns the name."""
    info = info or {}
    src = os.path.abspath(src)
    name = os.path.basename(src)
    try:
        with open(os.path.join(src, "package.toml"), "rb") as f:
            m = tomllib.load(f)
    except (OSError, tomllib.TOMLDecodeError) as e:
        raise Refused("%s: package.toml: %s" % (name, e))
    if m.get("name") != name or not NAME.match(name):
        raise Refused("%s: package.toml says name %r" % (name, m.get("name")))
    if m.get("kind") != "capability" or not m.get("module"):
        raise Refused("%s: only a capability package with a module is vendored" % name)
    mod = str(m["module"])
    if not NIX_FILE.match(mod) or not os.path.isfile(os.path.join(src, mod)):
        raise Refused("%s: module %s is missing" % (name, mod))
    hashes = nix_hashes(src)
    for base, dirs, files in os.walk(src):
        for n in dirs + files:
            if os.path.islink(os.path.join(base, n)):
                raise Refused("%s: %s is a link" % (name, n))
    dest = os.path.join(vendor_dir(checkout), name)
    tmp = os.path.join(vendor_dir(checkout), ".new-" + name)
    os.makedirs(vendor_dir(checkout), exist_ok=True)
    if os.path.lexists(tmp):
        rm_tree(tmp)
    shutil.copytree(src, tmp, symlinks=False)
    for base, dirs, files in os.walk(tmp):
        os.chmod(base, 0o755)
        for n in files:
            os.chmod(os.path.join(base, n), 0o644)
    if os.path.lexists(dest):
        rm_tree(dest)
    os.rename(tmp, dest)
    lock = read_lock(checkout)
    e = {"version": m.get("version")}
    for k in ORDER[1:]:
        if info.get(k):
            e[k] = info[k]
    e["nix"] = hashes
    lock[name] = e
    write_lock(checkout, lock)
    return name


def unvendor(name, checkout):
    if not NAME.match(name):
        raise Refused("not a package name: %s" % name)
    dest = os.path.join(vendor_dir(checkout), name)
    if os.path.lexists(dest):
        rm_tree(dest)
    lock = read_lock(checkout)
    if name in lock:
        del lock[name]
        write_lock(checkout, lock)
    for d in (vendor_dir(checkout), os.path.join(checkout, "vendor")):
        try:
            os.rmdir(d)          # only when empty
        except OSError:
            pass


def problems(checkout):
    """[(name, text)]: a vendored folder and the lock must agree exactly (what capabilities/default.nix asserts at evaluation)."""
    out = []
    lock = read_lock(checkout)
    d = vendor_dir(checkout)
    have = sorted(n for n in os.listdir(d) if os.path.isdir(os.path.join(d, n)) and not n.startswith(".")) if os.path.isdir(d) else []
    for n in have:
        if n not in lock:
            out.append((n, "vendored but not in the lock"))
    for n, e in sorted(lock.items()):
        if n not in have:
            out.append((n, "in the lock but not vendored"))
            continue
        try:
            now = nix_hashes(os.path.join(d, n))
        except Refused as ex:
            out.append((n, str(ex)))
            continue
        want = e.get("nix", {})
        for f in sorted(set(now) | set(want)):
            if f not in want:
                out.append((n, "%s is not in the lock" % f))
            elif f not in now:
                out.append((n, "%s is missing" % f))
            elif now[f] != want[f]:
                out.append((n, "%s differs from the lock" % f))
    return out


def main(argv):
    if not argv:
        print(__doc__)
        return 1

    def opt(k):
        return argv[argv.index(k) + 1] if k in argv and argv.index(k) + 1 < len(argv) else None
    cmd, to = argv[0], opt("--to")
    try:
        if cmd == "vendor" and opt("--from") and to:
            info = {k: opt("--" + k) for k in ("repo", "tag", "commit", "tree")}
            print(vendor(opt("--from"), to, info))
        elif cmd == "unvendor" and len(argv) > 1 and to:
            unvendor(argv[1], to)
        elif cmd == "check" and to:
            p = problems(to)
            for n, t in p:
                print("%s\t%s" % (n, t))
            return 1 if p else 0
        else:
            print(__doc__)
            return 1
    except Refused as e:
        print(str(e), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
