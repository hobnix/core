#!/usr/bin/env python3
"""systemd confinement of extension services, derived from the declared permissions (ADR 0014 step 2, docs/PLAN-extensions-access.md step 10).

`hs ext start` and `hs ext enable` write the text this prints as a drop-in of hs-ext-svc@<name>.service (scripts/ext.sh), so the properties
follow the manifest and nothing is generated by hand. Python stdlib only.

  ext_confine.py props [--] [PERMISSION ...]               the same properties, one per line (`systemd-run -p` of a confined command)
  ext_confine.py dropin --name N [--] [PERMISSION ...]     the drop-in text; PERMISSION is one entry of `permissions` (a lone "-" = the package
                                                           declares none). Exit 1 and the reason on stderr for a path that is not allowed.

The mapping (what systemd gives, nothing more):
  always                 ProtectSystem=strict, ProtectHome=yes, PrivateTmp=yes, NoNewPrivileges=yes, CapabilityBoundingSet= (none),
                         PrivateDevices=yes, ReadWritePaths=-<state dir of the bridge>
  secrets (#947)         TemporaryFileSystem=/var/lib/hs:ro (granted paths below it come back through BindPaths/BindReadOnlyPaths) and
                         InaccessiblePaths=-/root -/etc/shadow -/etc/gshadow -/etc/ssh -/etc/nixos. A grant that overlaps these is refused
                         (fs.write also /etc, /boot, /nix); /var/lib/hs/ext and /var/lib/hs/ext-svc stay grantable. Not limited: the network.
  fs.write:<path>        ReadWritePaths=-<path>
  fs.read:<path>         ReadOnlyPaths=-<path>     (the file system is read only under ProtectSystem=strict; this lists what is meant to be read)
  devices:gpu            PrivateDevices=no, DevicePolicy=closed, DeviceAllow=char-drm rw (only the declared device classes)
  net:<x>                nothing: declared only (D6); written as a comment
  everything else        nothing (web.*, events.*, host, secrets are not systemd's business)
A package without `permissions` gets the always-part and nothing else. A path must be absolute, without "..", ".", "//" or spaces, and not "/".
The leading "-" makes systemd skip a path that does not exist yet instead of refusing to start the unit.
"""
import re
import sys

STATE = "/var/lib/hs/ext-svc"      # the bridge (scripts/lib/ext_service.py) keeps its state here
PATH = re.compile(r"^/[A-Za-z0-9._/-]+$")
DEVICES = {"gpu": ["char-drm rw"]}
# Secrets: a grant (fs.read or fs.write) that is, lies below or contains one of these is refused (#947). The unit hides them too (properties()).
SECRET = ["/var/lib/hs", "/root", "/etc/shadow", "/etc/gshadow", "/etc/ssh", "/etc/nixos"]
SECRET_OPEN = ["/var/lib/hs/ext", "/var/lib/hs/ext-svc"]       # state of extensions: may be granted although /var/lib/hs is secret
NO_WRITE = ["/etc", "/boot", "/nix"]                           # fs.write only: system files (reading /etc/hs and the like stays possible)


def check_path(p):
    """The problem with a path, or None."""
    if isinstance(p, str) and p.strip("/") == "" and p:
        return "path %r is not allowed: it would open the whole file system" % p
    if not isinstance(p, str) or not PATH.match(p):
        return "path %r is not allowed (absolute, letters, digits and . _ - / only)" % (p,)
    parts = p.split("/")[1:]
    if parts[-1] == "":
        parts = parts[:-1]
    if not parts:
        return "path '/' is not allowed: it would open the whole file system"
    if any(x in ("", ".", "..") for x in parts):
        return "path %r is not allowed (no '..', '.' or '//')" % p
    return None


def _under(p, d):
    return p == d or p.startswith(d + "/")


def check_secret(key, p):
    """The problem with a well-formed path `p` of `key` (fs.read|fs.write) that touches a secret location, or None."""
    p = p.rstrip("/") or p
    if any(_under(p, o) for o in SECRET_OPEN):
        return None
    for d in SECRET + (NO_WRITE if key == "fs.write" else []):
        if _under(p, d) or _under(d, p):
            return "path %r is not allowed: it overlaps %s, which holds secrets or system files (grant a path below /var/lib/hs/ext/<name> instead)" % (p, d)
    return None


def properties(perms):
    """([Service] property lines, [comment lines], None) or (None, None, problem). perms is None when the package declares none.
    The one mapping: the drop-in of a service and `systemd-run -p` of a confined command (ext_proto.py) both use it."""
    write, read, devs, net = [], [], [], None
    for p in perms or []:
        key, _, arg = str(p).partition(":")
        if key in ("fs.write", "fs.read"):
            bad = check_path(arg)
            if bad:
                return None, None, "%s: %s" % (key, bad)
            bad = check_secret(key, arg)
            if bad:
                return None, None, "%s: %s" % (key, bad)
            lst = write if key == "fs.write" else read
            arg = arg.rstrip("/") or arg
            if arg not in lst:
                lst.append(arg)
        elif key == "devices":
            if arg not in DEVICES:
                return None, None, "devices: unknown device %r" % arg
            if arg not in devs:
                devs.append(arg)
        elif key == "net":
            net = arg
    out = ["ProtectSystem=strict", "ProtectHome=yes", "PrivateTmp=yes", "NoNewPrivileges=yes", "CapabilityBoundingSet="]
    if devs:
        out += ["PrivateDevices=no", "DevicePolicy=closed"]
        out += ["DeviceAllow=" + d for g in devs for d in DEVICES[g]]
    else:
        out.append("PrivateDevices=yes")
    # /var/lib/hs becomes an empty read-only tmpfs; only the granted paths below it are bound back in. The other secrets are made inaccessible.
    out.append("TemporaryFileSystem=/var/lib/hs:ro")
    out.append("InaccessiblePaths=" + " ".join("-" + x for x in SECRET if x != "/var/lib/hs"))
    rw = [STATE] + write
    rw_other = [x for x in rw if not _under(x, "/var/lib/hs")]
    if rw_other:
        out.append("ReadWritePaths=" + " ".join("-" + x for x in rw_other))
    out.append("BindPaths=" + " ".join("-" + x for x in rw if _under(x, "/var/lib/hs")))
    ro_hs = [x for x in read if _under(x, "/var/lib/hs")]
    if ro_hs:
        out.append("BindReadOnlyPaths=" + " ".join("-" + x for x in ro_hs))
    ro = [x for x in read if not _under(x, "/var/lib/hs")]
    if ro:
        out.append("ReadOnlyPaths=" + " ".join("-" + x for x in ro))
    notes = ["# net=%s is declared only: nothing here limits the network" % net] if net else []
    return out, notes, None


def dropin(name, perms):
    """(text, None) or (None, problem). perms is None when the package declares none."""
    props, notes, bad = properties(perms)
    if bad:
        return None, bad
    head = ["# Written by hs ext (scripts/lib/ext_confine.py) from the permissions of %s. Do not edit; it is rewritten at every start." % name,
            "[Service]"]
    return "\n".join(head + props + notes) + "\n", None


def main(argv):
    if argv[:1] == ["props"]:
        rest = [a for a in argv[1:] if a != "--"]
        props, _, bad = properties(None if rest == ["-"] else rest)
        if bad:
            print("ext_confine.py: " + bad, file=sys.stderr)
            return 1
        sys.stdout.write(chr(10).join(props) + chr(10))
        return 0
    if argv[:1] != ["dropin"] or "--name" not in argv:
        print("usage: ext_confine.py dropin --name N [--] [PERMISSION ...]", file=sys.stderr)
        return 2
    i = argv.index("--name")
    name = argv[i + 1] if i + 1 < len(argv) else ""
    if not re.match(r"^[a-z][a-z0-9-]{0,40}$", name):
        print("ext_confine.py: bad package name", file=sys.stderr)
        return 2
    rest = [a for j, a in enumerate(argv[1:], 1) if j not in (i, i + 1) and a != "--"]
    perms = None if rest == ["-"] else rest
    text, bad = dropin(name, perms)
    if bad:
        print("ext_confine.py: " + bad, file=sys.stderr)
        return 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
