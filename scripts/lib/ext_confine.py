#!/usr/bin/env python3
"""systemd confinement of extension services, derived from the declared permissions (ADR 0014 step 2, docs/PLAN-extensions-access.md step 10).

`hs ext start` and `hs ext enable` write the text this prints as a drop-in of hs-ext-svc@<name>.service (scripts/ext.sh), so the properties
follow the manifest and nothing is generated by hand. Python stdlib only.

  ext_confine.py props [--dynamic] [--name N] [--] [PERMISSION ...]               the same properties, one per line (`systemd-run -p` of a confined command)
  ext_confine.py dropin [--dynamic] --name N [--] [PERMISSION ...]     the drop-in text; PERMISSION is one entry of `permissions` (a lone "-" = the package
                                                           declares none). Exit 1 and the reason on stderr for a path that is not allowed.

The mapping (what systemd gives, nothing more):
  always                 ProtectSystem=strict, ProtectHome=yes, PrivateTmp=yes, NoNewPrivileges=yes, CapabilityBoundingSet= (none),
                         PrivateDevices=yes, ReadWritePaths=-<state dir of the bridge>
  secrets (#947)         TemporaryFileSystem=/var/lib/hs:ro (granted paths below it come back through BindPaths/BindReadOnlyPaths) and
                         InaccessiblePaths=-/root -/etc/shadow -/etc/gshadow -/etc/ssh -/etc/nixos -/var/lib/hs-vault -/run/hs-ext-cred. A grant that overlaps these is refused
                         (fs.write also /etc, /boot, /nix); /var/lib/hs/ext, /var/lib/hs/ext-svc and /var/lib/hs/<package name> stay grantable Not limited: the network.
  fs.write:<path>        ReadWritePaths=-<path>
  fs.read:<path>         ReadOnlyPaths=-<path>     (the file system is read only under ProtectSystem=strict; this lists what is meant to be read)
  hardening              ProtectKernelTunables/Modules/Logs, ProtectControlGroups, ProtectClock, ProtectHostname,
                         RestrictNamespaces, RestrictRealtime, RestrictSUIDSGID, LockPersonality, SystemCallArchitectures=native,
                         SystemCallFilter=~@mount @swap ... (deny list, EPERM), RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK (HARDEN); no IPAddressAllow/Deny
  devices:gpu            PrivateDevices=no, DevicePolicy=closed, DeviceAllow=char-drm rw (only the declared device classes)
  --dynamic              (not used by a running service yet, #1134) DynamicUser=yes, User=hsx-<name>, StateDirectory=hs-ext/<name> (0700, UMask=0077),
                         BindPaths=-/var/lib/hs-ext/<name>:/var/lib/hs/<name> instead of the bridge state; devices:gpu adds SupplementaryGroups=render video;
                         fs.write only below /var/lib/hs/<name> (anything else: ext.dynamic-write), no line for it
  net:<x>                nothing: declared only (D6); written as a comment
  everything else        nothing (web.*, events.*, host, secrets are not systemd's business)
A package without `permissions` gets the always-part and nothing else. A path must be absolute, without "..", ".", "//" or spaces, and not "/".
The leading "-" makes systemd skip a path that does not exist yet instead of refusing to start the unit.
"""
import hashlib
import importlib.util
import os
import re
import sys

STATE = "/var/lib/hs/ext-svc"      # the bridge (scripts/lib/ext_service.py) keeps its state here
EXT_STATE = "/var/lib/hs-ext"      # the dynamic user's view of its state: StateDirectory=hs-ext/<name> (ext_state.py moves the old folder there)
GPU_GROUPS = "render video"        # SupplementaryGroups of a dynamic unit that declares devices:gpu
PATH = re.compile(r"^/[A-Za-z0-9._/-]+$")
DEVICES = {"gpu": ["char-drm rw"]}
# Hardening that no declared permission needs to be off (ADR 0031 decision 5, without the dynamic user). Unix sockets (the bridge pipe, incus, the
# journal) stay: AF_UNIX; net is not filtered here (a firewall decision), so AF_INET and AF_INET6 stay; AF_NETLINK stays for the tools a command runs
# (ip, getifaddrs). Left out on purpose, because a violation cannot be seen before a run on hardware: the allow list SystemCallFilter=@system-service
# (a call outside it kills the process with SIGSYS, silently; a deny list of the system-changing groups is used instead, and SystemCallErrorNumber makes
# a refused call an error), ProtectProc=invisible and ProcSubset=pid (an `hs` call or a tool that reads /proc/meminfo or another process), and
# MemoryDenyWriteExecute (Python). The riskiest remaining flags: RestrictNamespaces, SystemCallFilter.
HARDEN = ["ProtectKernelTunables=yes", "ProtectKernelModules=yes", "ProtectKernelLogs=yes", "ProtectControlGroups=yes", "ProtectClock=yes", "ProtectHostname=yes", "RestrictNamespaces=yes", "RestrictRealtime=yes", "RestrictSUIDSGID=yes", "LockPersonality=yes",
          "SystemCallArchitectures=native", "SystemCallFilter=~@mount @swap @reboot @module @raw-io @cpu-emulation @debug @obsolete",
          "SystemCallErrorNumber=EPERM", "RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK"]
# Secrets: a grant (fs.read or fs.write) that is, lies below or contains one of these is refused (#947). The unit hides them too (properties()).
# /var/lib/hs-vault is the vault (unlocked keys); /run/hs-ext-cred holds the short-lived key copies of the other services (ext_service.py): a service runs as
# root, so only InaccessiblePaths keeps it out of them
HIDDEN = ["/var/lib/hs", "/root", "/etc/shadow", "/etc/gshadow", "/etc/ssh", "/etc/nixos", "/var/lib/hs-vault", "/run/hs-ext-cred"]   # what the unit hides
# a grant may never reach the state of another package (the dynamic user's folders, ADR 0031 decision 4) either; not hidden, the unit binds its own in
SECRET = HIDDEN + ["/var/lib/private", EXT_STATE]
SECRET_OPEN = ["/var/lib/hs/ext", "/var/lib/hs/ext-svc"]       # state of extensions: may be granted although /var/lib/hs is secret
NO_WRITE = ["/etc", "/boot", "/nix"]                           # fs.write only: system files (reading /etc/hs and the like stays possible)


def check_path(p):
    """The problem with a path, or None."""
    if isinstance(p, str) and p.strip("/") == "" and p:
        return "path %r is not allowed: it would open the whole file system" % p
    if not isinstance(p, str) or not PATH.fullmatch(p):
        return "path %r is not allowed (absolute, letters, digits and . _ - / only)" % (p,)
    parts = p.split("/")[1:]
    if parts[-1] == "":
        parts = parts[:-1]
    if not parts:
        return "path '/' is not allowed: it would open the whole file system"
    if any(x in ("", ".", "..") for x in parts):
        return "path %r is not allowed (no '..', '.' or '//')" % p
    return None


def _under(p, d):
    return p == d or p.startswith(d + "/")


def check_secret(key, p, name=None):
    """The problem with a well-formed path `p` of `key` (fs.read|fs.write) of package `name` that touches a secret location, or None.
    The deny list is the three lists above; the only way in is /var/lib/hs/<its own name> (and SECRET_OPEN)."""
    p = p.rstrip("/") or p
    if name and _under(p, "/var/lib/hs/" + name):
        return None
    if any(_under(p, o) for o in SECRET_OPEN):
        return None
    for d in SECRET + (NO_WRITE if key == "fs.write" else []):
        if _under(p, d) or _under(d, p):
            return "path %r is not allowed: it overlaps %s, which holds secrets or system files (grant a path below /var/lib/hs/<package name> or /var/lib/hs/ext/<name> instead)" % (p, d)
    return None


def unit_user(name):
    """The dynamic user of a package: hsx-<name>, at most 31 characters. A longer name is cut to 14 characters and gets "_" and 12 hex digits of the
    hash of the FULL name: "_" cannot be in a package name, so no short name equals a cut one, and two long names differ in the hash (48 bits).
    One user name is one uid: it must never be shared by two packages."""
    u = "hsx-" + name
    if len(u) > 31:
        u = "hsx-" + name[:14] + "_" + hashlib.sha256(name.encode()).hexdigest()[:12]
    return u


def state_source(name):
    """Where the unit's own state folder is bound from. If the VM stage shows systemd does not resolve the link, this is the one edit:
    /var/lib/private/hs-ext/<name>."""
    return "%s/%s" % (EXT_STATE, name)


def _bad_dynamic_name(name):
    """The problem with the package name of a dynamic unit (a name of the core's own /var/lib/hs folders, ext_state.RESERVED), or None."""
    if not name:
        return "a dynamic unit needs the package name"
    spec = importlib.util.spec_from_file_location("ext_state", os.path.join(os.path.dirname(os.path.abspath(__file__)), "ext_state.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod._bad_name(name)


def properties(perms, name=None, dynamic=False):
    """([Service] property lines, [comment lines], None) or (None, None, problem). perms is None when the package declares none.
    The one mapping: the drop-in of a service and `systemd-run -p` of a confined command (ext_proto.py) both use it.
    dynamic=True (needs name): the unit runs as DynamicUser hsx-<name>; it may write only /var/lib/hs/<name> (its StateDirectory), nothing else.
    Not used by a running service yet (#1134 slice 2)."""
    if dynamic:
        bad = _bad_dynamic_name(name)
        if bad:
            return None, None, bad
    write, read, devs, net = [], [], [], None
    for p in perms or []:
        if re.search(r"[\x00-\x1f\x7f]", str(p)):
            return None, None, "a permission has no control characters: %r" % (p,)
        key, _, arg = str(p).partition(":")
        if key in ("fs.write", "fs.read"):
            bad = check_path(arg)
            if bad:
                return None, None, "%s: %s" % (key, bad)
            bad = check_secret(key, arg, name)
            if bad:
                return None, None, "%s: %s" % (key, bad)
            lst = write if key == "fs.write" else read
            arg = arg.rstrip("/") or arg
            own = dynamic and _under(arg, "/var/lib/hs/" + name)
            if dynamic and not own and (any(_under(arg, d) for d in ("/var/lib/hs", EXT_STATE, "/var/lib/private")) or _under("/var/lib/hs/" + name, arg)):
                return None, None, ("ext.dynamic-read: %s:%s is not allowed for a service or confined command: the state of the server and of the other "
                                    "extensions stays closed; only /var/lib/hs/%s is its own" % (key, arg, name))
            if dynamic and key == "fs.write" and not own:
                return None, None, ("ext.dynamic-write: fs.write:%s is not allowed for a service or confined command: it runs as its own user "
                                    "and may write only /var/lib/hs/%s" % (arg, name))
            if own:
                continue      # the state bind covers it
            if arg not in lst:
                lst.append(arg)
        elif key == "devices":
            if arg not in DEVICES:
                return None, None, "devices: unknown device %r" % arg
            if arg not in devs:
                devs.append(arg)
        elif key == "net":
            net = arg
    out = ["ProtectSystem=strict", "ProtectHome=yes", "PrivateTmp=yes", "NoNewPrivileges=yes", "CapabilityBoundingSet="]
    out += HARDEN
    if devs:
        out += ["PrivateDevices=no", "DevicePolicy=closed"]
        out += ["DeviceAllow=" + d for g in devs for d in DEVICES[g]]
    else:
        out.append("PrivateDevices=yes")
    if dynamic:
        out += ["DynamicUser=yes", "User=" + unit_user(name), "StateDirectory=hs-ext/" + name, "StateDirectoryMode=0700", "UMask=0077", "ProtectProc=invisible"]
        # ProtectProc=invisible: the unit cannot see the processes of other users (another extension, root). Without ProcSubset=pid (ADR 0031
        # decision 5 left it out: a tool reading /proc/meminfo). Own StateDirectory only: /var/lib/private is 0700 root and the other folders are
        # owned by other uids; whether that is enough or the VM stage needs an InaccessiblePaths is [nv] (see nested_stages.py confine_dynamic)
        if devs:
            out.append("SupplementaryGroups=" + GPU_GROUPS)
    # /var/lib/hs becomes an empty read-only tmpfs; only the granted paths below it are bound back in. The other secrets are made inaccessible.
    out.append("TemporaryFileSystem=/var/lib/hs:ro")
    out.append("InaccessiblePaths=" + " ".join("-" + x for x in HIDDEN if x != "/var/lib/hs"))
    rw = ([state_source(name) + ":/var/lib/hs/" + name] if dynamic else [STATE]) + write
    rw_other = [x for x in write if not _under(x, "/var/lib/hs")] if dynamic else [x for x in rw if not _under(x, "/var/lib/hs")]
    if rw_other:
        out.append("ReadWritePaths=" + " ".join("-" + x for x in rw_other))
    out.append("BindPaths=" + " ".join("-" + x for x in rw if dynamic or _under(x, "/var/lib/hs")))
    ro_hs = [x for x in read if _under(x, "/var/lib/hs")]
    if ro_hs:
        out.append("BindReadOnlyPaths=" + " ".join("-" + x for x in ro_hs))
    ro = [x for x in read if not _under(x, "/var/lib/hs")]
    if ro:
        out.append("ReadOnlyPaths=" + " ".join("-" + x for x in ro))
    notes = ["# net=%s is declared only: nothing here limits the network" % net] if net else []
    return out, notes, None


def dropin(name, perms, dynamic=False):
    """(text, None) or (None, problem). perms is None when the package declares none."""
    props, notes, bad = properties(perms, name, dynamic)
    if bad:
        return None, bad
    head = ["# Written by hs ext (scripts/lib/ext_confine.py) from the permissions of %s. Do not edit; it is rewritten at every start." % name,
            "[Service]"]
    return "\n".join(head + props + notes) + "\n", None


def main(argv):
    head = argv[:argv.index("--")] if "--" in argv else argv      # options only before "--": after it every word is a permission
    dynamic = "--dynamic" in head
    if dynamic:
        argv = [a for i, a in enumerate(argv) if a != "--dynamic" or i >= len(head)]
    if argv[:1] == ["props"]:
        args = argv[1:]
        name = None
        if "--name" in args:
            i = args.index("--name")
            name = args[i + 1] if i + 1 < len(args) else None
            args = args[:i] + args[i + 2:]
        rest = [a for a in args if a != "--"]
        props, _, bad = properties(None if rest == ["-"] else rest, name, dynamic)
        if bad:
            print("ext_confine.py: " + bad, file=sys.stderr)
            return 1
        sys.stdout.write(chr(10).join(props) + chr(10))
        return 0
    if argv[:1] != ["dropin"] or "--name" not in argv:
        print("usage: ext_confine.py dropin --name N [--] [PERMISSION ...]", file=sys.stderr)
        return 2
    i = argv.index("--name")
    name = argv[i + 1] if i + 1 < len(argv) else ""
    if not re.match(r"^[a-z][a-z0-9-]{0,40}$", name):
        print("ext_confine.py: bad package name", file=sys.stderr)
        return 2
    rest = [a for j, a in enumerate(argv[1:], 1) if j not in (i, i + 1) and a != "--"]
    perms = None if rest == ["-"] else rest
    text, bad = dropin(name, perms, dynamic)
    if bad:
        print("ext_confine.py: " + bad, file=sys.stderr)
        return 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
